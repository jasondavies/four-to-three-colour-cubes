#!/usr/bin/env python3
"""Draw the 28-cube obstruction for the paper (TikZ) and README (SVG).

Faces are read from `lowerFamily` in the Lean source, so the drawing cannot
drift from the formal counterexample. Pass a directory to write elsewhere;
`scripts/check-generated.py` uses this to compare the checked-in files.
"""
from collections import Counter
import json
import math
from pathlib import Path
import re
import sys

from cube_geometry import ROT, canonical, require, rotate

ROOT = Path(__file__).resolve().parents[1]
# Okabe-Ito colours: distinguishable with colour-blindness, and dark digits stay
# legible on each. Digits carry the colour identity in greyscale.
COLOURS = ('E69F00', '56B4E9', '009E73', 'F0E442')
# (column, row) -> face index in the order +x,-x,+y,-y,+z,-z. Seen from outside
# with +z up, +y lies to the right of +x. Swapping sides would draw the mirror
# image, which is the other obstruction.
NET = {(1, 0): 4, (0, 1): 3, (1, 1): 0, (2, 1): 2, (3, 1): 1, (1, 2): 5}
NET_WIDTH = 4
NET_HEIGHT = 3
NET_GAP = 1
COPIES = 7


def obstruction():
    """Return the printed tuples, read from Lean and checked against the fixture."""
    source = (ROOT / 'ThreeColour/Family.lean').read_text(encoding='utf-8')
    block = re.search(r'def lowerFamily.*?\(!\[(.*?)\] :', source, re.S)
    require(block is not None, 'lowerFamily not found')
    tuples = [tuple(map(int, t.split(',')))
              for t in re.findall(r'!\[([0-9,]+)\]', block.group(0))]
    require(len(tuples) == 4 and all(len(t) == 6 for t in tuples), 'Unexpected lowerFamily')
    fixture = json.loads((ROOT / 'data/lower-obstruction.json').read_text(encoding='utf-8'))
    require({(tuple(e['faces']), e['count']) for e in fixture['collection']}
            == {(t, COPIES) for t in tuples}, 'Fixture differs from lowerFamily')
    return tuples


def corner_view(cube):
    """Rotate a cube so its repeated colour occupies the +x,+y,+z corner."""
    colour, multiplicity = Counter(cube).most_common(1)[0]
    require(multiplicity == 3, 'Expected a colour on exactly three faces')
    views = [v for v in (rotate(cube, r) for r in ROT)
             if v[0] == v[2] == v[4] == colour]
    require(views, 'Repeated colour does not occupy a corner')
    view = min(views)
    require(canonical(view) == canonical(cube), 'Rotation changed the variety')
    return view


def word(cube):
    return ''.join(map(str, cube))


def net_cells(cubes):
    """Yield (cube index, column, row, colour) across one row of nets."""
    for i, cube in enumerate(cubes):
        view = corner_view(cube)
        offset = i * (NET_WIDTH + NET_GAP)
        for (column, row), face in NET.items():
            yield i, offset + column, row, view[face]


def tikz(cubes):
    lines = ['% Generated by scripts/generate_figure.py from lowerFamily; do not edit.']
    lines += [f'\\definecolor{{cube{i}}}{{HTML}}{{{c}}}' for i, c in enumerate(COLOURS)]
    lines.append('\\begin{tikzpicture}[x=6.5mm,y=-6.5mm,line width=.4pt]')
    for _, x, y, colour in net_cells(cubes):
        lines.append(f'\\filldraw[fill=cube{colour}] ({x},{y}) rectangle ++(1,1);')
        lines.append(f'\\node at ({x}.5,{y}.5) {{${colour}$}};')
    for i, cube in enumerate(cubes):
        x = i * (NET_WIDTH + NET_GAP) + NET_WIDTH / 2
        lines.append(f'\\node at ({x},{NET_HEIGHT}.6) {{${COPIES}\\times{word(cube)}$}};')
    lines.append('\\end{tikzpicture}')
    return '\n'.join(lines) + '\n'


def number(value):
    return f'{value:.2f}'.rstrip('0').rstrip('.')


def svg_digit(x, y, colour):
    return (f'<text x="{number(x)}" y="{number(y)}" text-anchor="middle" '
            f'dominant-baseline="central">{colour}</text>')


def svg(cubes):
    unit = 38
    margin = 28
    title = 44
    # The target D(0,1,2), with opposite faces equal: left +x, right +y, top +z.
    # Screen axes make +x,+y,+z counterclockwise from outside, as in the paper.
    def project(x, y, z):
        return ((y - x) * math.cos(math.radians(30)) * unit,
                ((x + y) * 0.5 - z) * unit)
    faces = (
        (0, lambda a, b: (2, a, 2 - b)),
        (1, lambda a, b: (2 - a, 2, 2 - b)),
        (2, lambda a, b: (a, b, 2)),
    )
    left = project(2, 0, 0)[0]
    right = project(0, 2, 0)[0]
    top = project(0, 0, 2)[1]
    bottom = project(2, 2, 0)[1]
    origin_x = margin - left
    origin_y = margin + title - top + (NET_HEIGHT * unit - (bottom - top)) / 2
    nets_x = origin_x + right + 2 * unit
    width = nets_x + (4 * NET_WIDTH + 3 * NET_GAP) * unit + margin
    height = margin + title + NET_HEIGHT * unit + 44 + margin

    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{number(width)}" '
           f'height="{number(height)}" viewBox="0 0 {number(width)} {number(height)}" '
           'role="img" aria-labelledby="t">',
           '<title id="t">A three-colour target beside four cube varieties, '
           'each repeated seven times, that cannot build any such target</title>',
           f'<rect width="{number(width)}" height="{number(height)}" rx="10" fill="#fff"/>',
           '<g font-family="Helvetica,Arial,sans-serif" font-size="16" fill="#111">']
    heading = f'<text x="{{}}" y="{margin + 12}" text-anchor="middle" font-size="17" font-weight="bold">{{}}</text>'
    out.append(heading.format(number(origin_x + (left + right) / 2), 'A target'))
    out.append(heading.format(
        number(nets_x + (4 * NET_WIDTH + 3 * NET_GAP) * unit / 2), 'An obstruction: 28 cubes'))
    out.append('<g stroke="#111" stroke-width="1.2" stroke-linejoin="round">')
    labels = []
    for colour, point in faces:
        for a in range(2):
            for b in range(2):
                corners = [project(*point(a + s, b + t)) for s, t in ((0, 0), (1, 0), (1, 1), (0, 1))]
                shifted = [(x + origin_x, y + origin_y) for x, y in corners]
                path = ' '.join(f'{number(x)},{number(y)}' for x, y in shifted)
                out.append(f'<polygon points="{path}" fill="#{COLOURS[colour]}"/>')
                labels.append(svg_digit(sum(x for x, _ in shifted) / 4,
                                        sum(y for _, y in shifted) / 4, colour))
    nets_y = margin + title
    for _, x, y, colour in net_cells(cubes):
        out.append(f'<rect x="{number(nets_x + x * unit)}" y="{number(nets_y + y * unit)}" '
                   f'width="{unit}" height="{unit}" fill="#{COLOURS[colour]}"/>')
        labels.append(svg_digit(nets_x + (x + 0.5) * unit, nets_y + (y + 0.5) * unit, colour))
    out.append('</g>')
    out += labels
    for i, cube in enumerate(cubes):
        x = nets_x + (i * (NET_WIDTH + NET_GAP) + NET_WIDTH / 2) * unit
        y = nets_y + NET_HEIGHT * unit + 26
        out.append(f'<text x="{number(x)}" y="{number(y)}" text-anchor="middle" '
                   f'dominant-baseline="central">{COPIES} × {word(cube)}</text>')
    out += ['</g>', '</svg>']
    return '\n'.join(out) + '\n'


def main():
    directory = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'paper'
    cubes = obstruction()
    (directory / 'obstruction-figure.tex').write_text(tikz(cubes), encoding='utf-8')
    (directory / 'obstruction-figure.svg').write_text(svg(cubes), encoding='utf-8')


if __name__ == '__main__':
    main()
